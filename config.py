def season_of(keyword: str, today=None) -> str:
    """키워드에 계절명이 있으면 그것, 없으면 현재 월 기준 계절(한국: 3-5봄,6-8여름,9-11가을,12-2겨울)."""
    for s in SEASONS:
        if s in keyword:
            return s
    m = (today or date.today()).month
    return SEASONS[(m - 3) % 12 // 3]
